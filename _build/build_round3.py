def main():
    doc = Document(SRC)
    R1.DOC = doc
    tpl3 = doc.tables[0]._tbl
    tpl5 = doc.tables[2]._tbl

    def H1(t):
        return R1.new_para(t, style="Heading 1")

    def H2(t):
        return R1.new_para(t, style="Heading 2", space_before=10.0)

    def P(t, **kw):
        return R1.new_para(t, **kw)

    def CAP(t):
        p = R1.new_para(t, align=WD_ALIGN_PARAGRAPH.CENTER, size=9.0)
        p.paragraph_format.keep_with_next = True
        return p

    def FIG(path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.keep_with_next = True
        p.add_run().add_picture(path, width=Inches(IMG_W))
        return p

    def TBL(template, head, rows, widths):
        doc.element.body.find(
            "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}sectPr"
        ).addprevious(R1.build_table(template, head, rows, widths))

    # =====================================================================
    H1("七、概要设计——体系结构与接口设计")
    P("本章回答三个问题：系统由哪几层组成、各层之间怎么调用（7.1）；部署时各部分跑在哪里（7.2）；"
      "代码怎么划分模块、模块之间靠什么接口协作（7.3、7.4）。第六节已经解决数据怎么存，"
      "本章解决程序怎么组织。")

    # ---- 7.1 -------------------------------------------------------------
    H2("7.1 总体架构")
    P("系统采用五层结构，自上而下为接入层、网关层、业务层、智能层与数据层，如图 7 所示。"
      "分层的核心目的是把“会变的部分”隔离出来：界面改动不影响业务，换大模型供应商不影响业务逻辑。")
    FIG(os.path.join(WS, "图7-体系结构图.png"))
    CAP("图 7  知屿校园平台体系结构图")

    CAP("表 19  各层组成与职责")
    TBL(tpl3, LAYER_HEAD, LAYER_ROWS, [900, 2450, 3794])

    P("三点设计取舍说明：")
    for t in (
        "（1）前端不直连数据库。所有读写都经网关进入业务层，这样权限校验只有一处，"
        "不会因为某个页面漏判而越权。",
        "（2）大模型调用被隔离在智能层。大模型响应慢、可能失败、按量计费，把它放在独立的智能层"
        "并用队列异步处理，业务写入不受它影响——这正是 NFR-05 要求的降级能力。",
        "（3）数据层按“读多写多”分开选型：结构化数据进 MySQL；会话与热点数据进 Redis；"
        "全文检索与摘要进检索引擎；图片与附件进对象存储。第六节的 18 张表只落在 MySQL，"
        "不承担全文检索职责。",
    ):
        P(t)

    P("技术选型建议（可按团队熟悉程度替换，不改变本节的分层结论）：前端 Vue 3 或 React；"
      "后端 Spring Boot（Java 17）；数据库 MySQL 8.0；缓存 Redis；检索引擎 Elasticsearch；"
      "对象存储 MinIO；大模型通过适配层对接，可替换为任一兼容服务。")

    # ---- 7.2 -------------------------------------------------------------
    H2("7.2 部署结构")
    P("部署如图 8 所示。起步阶段可用一台云服务器 + Docker Compose 跑通全部组件，"
      "访问量上来后按“无状态应用横向扩、数据库纵向扩”的顺序演进。")
    FIG(os.path.join(WS, "图8-部署图.png"))
    CAP("图 8  知屿校园平台部署图")

    for t in (
        "（1）应用服务器部署 2 个实例，由 Nginx 做负载均衡；应用本身无状态，会话信息放在 Redis，"
        "因此可以随时增减实例。",
        "（2）AI 智能体服务独立部署，原因有二：它需要长时间占用网络与 CPU 调大模型，"
        "和业务服务抢资源会拖慢接口；独立部署后可以单独限流、单独重启，故障不扩散。",
        "（3）MySQL 采用主从，主库承担写、从库承担列表查询；Redis 承担会话与热点缓存；"
        "检索引擎与对象存储独立进程，均可替换。",
        "（4）大模型服务是外部依赖，用虚线表示在系统边界之外；它不可用时系统降级（见 7.4.3）。",
    ):
        P(t)

    # ---- 7.3 -------------------------------------------------------------
    H2("7.3 功能模块划分")
    P("按“一个模块对应一段可独立开发、独立测试的功能”的原则，把系统划分为 8 个模块，"
      "如图 9 所示。模块划分与第二节数据流图的加工编号一一对应，因此可以直接作为分工依据。")
    FIG(os.path.join(WS, "图9-功能结构图.png"))
    CAP("图 9  知屿校园平台功能结构图")

    CAP("表 20  功能模块清单")
    TBL(tpl5, MOD_HEAD, MOD_ROWS, [500, 1200, 1900, 1000, 2544])

    P("说明：M5 智能体是唯一与其他模块“异步耦合”的模块——它不直接被用户调用，"
      "而是消费消息与帖子产生的事件；M8 审核与运营则是 M5 的下游，接收违规预警与用户举报。"
      "这条异步链路对应表 20 中 M5 与 M8 的“对应加工”列。")

    # ---- 7.4 -------------------------------------------------------------
    H2("7.4 接口设计")
    P("接口是对外契约，也是前后端协作与测试用例的来源。本节先给通用约定，再列接口清单、"
      "大模型服务契约与统一错误码。")

    H2("7.4.1 通用约定")
    for t in (
        "（1）风格：RESTful + JSON，资源名用复数，版本号放在路径中（/api/v1），"
        "后续不兼容变更时升级为 v2，旧版本保留一个迭代周期。",
        "（2）鉴权：除标注“公开”的接口外，请求头携带 Authorization: Bearer <JWT>，"
        "令牌中含用户ID与角色，网关统一校验，业务层只做资源归属校验。",
        "（3）分页：列表统一用游标分页（cursor + limit，limit 默认 20、上限 50），"
        "聊天记录以 (room_id, id) 为游标，避免深分页带来的性能问题。",
        "（4）时间：统一 ISO-8601 带时区（如 2026-09-30T14:08:14+08:00）。",
        "（5）幂等：点赞、收藏、加入聊天室等重复操作返回成功而非报错，"
        "与表 18 中 like_record、favorite 的复合主键约束一致。",
        "（6）响应体：统一为 {code, message, data, traceId}，code=0 表示成功，错误码见表 23。",
        "（7）限流：按用户与 IP 双维度限流，写接口 10 次/秒，读接口 50 次/秒，超出返回 42901。",
    ):
        P(t)

    H2("7.4.2 接口清单")
    P("共 23 个接口，覆盖第一节 14 个用例的主流程；举报与审核相关接口中，"
      "A-23 属二期（与 1.5 节 UC-13 的 P2 定位一致）。")
    CAP("表 21  对外接口清单")
    TBL(tpl5, API_HEAD, API_ROWS, [520, 700, 2100, 2050, 1774])

    H2("7.4.3 大模型服务接口契约")
    P("智能体调用大模型是本系统唯一的外部依赖调用，必须把“怎么调、失败了怎么办”写死，"
      "否则线上很容易因为对方限流或返回格式变化而拖垮业务。")
    CAP("表 22  大模型服务接口契约")
    TBL(tpl3, LLM_HEAD, LLM_ROWS, [1100, 2500, 3544])

    H2("7.4.4 统一错误码")
    P("错误码按“谁的问题”分段：4xxxx 为调用方问题，5xxxx 为服务端问题，"
      "前端据此决定是提示用户、重试还是跳转。")
    CAP("表 23  统一错误码")
    TBL(tpl3, ERR_HEAD, ERR_ROWS, [800, 2200, 4144])

    # ---- 7.5 -------------------------------------------------------------
    H2("7.5 本章与前后章节的对应关系")
    P("本章不是孤立的一章，它与前面的需求、数据设计形成一条可追溯的链条，"
      "对照关系见表 20 的“对应加工”“主要涉及的表”两列：")
    for t in (
        "（1）需求 → 模块：第一节的 14 个用例（表 3）分配到表 20 的 8 个模块，"
        "每个用例至少落在一个模块内，没有悬空需求。",
        "（2）加工 → 模块：第二节数据流图的加工 1~7 与 2.1~6.2 编号直接写在表 20，"
        "说明数据分析与功能划分是同一套划分口径。",
        "（3）模块 → 数据：表 20 最后一列列出每个模块主要读写的表，"
        "与第六节 18 张表一一对应，没有模块读写不存在的表。",
        "（4）接口 → 用例：表 21 的 23 个接口覆盖 14 个用例的主流程；"
        "下一轮测试用例可直接按接口逐条设计，覆盖正常流、备选流与错误码。",
    ):
        P(t)
    P("至此概要设计的三块内容（数据设计、结构设计、接口设计）全部完成，"
      "下一步进入详细设计：类图、关键算法伪代码与状态图。")

    doc.save(OUT)
    print("saved:", OUT)


if __name__ == "__main__":
    main()
