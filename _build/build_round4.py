import os
import sys

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_round1 as R1  # noqa: E402

WS = r"C:\Users\saxtul\Documents\ds harness区\知屿校园"
SRC = os.path.join(WS, "知屿校园-需求分析与建模实验报告-第3轮修订.docx")
OUT = os.path.join(WS, "知屿校园-需求分析与建模实验报告-第4轮修订.docx")
IMG_W = 6.30

CLASS_HEAD = ["类", "职责", "关键方法"]
CLASS_ROWS = [
    ["User 用户", "账号、角色与口令；登录签令与资料维护", "login()、updateProfile()"],
    ["ChatRoom 聊天室", "房间属性与成员关系；成员加入、发言权限判定", "join()、sendMessage()"],
    ["Message 消息", "一条聊天消息；屏蔽与投递索引", "hide()、toIndex()"],
    ["Post 帖子", "帖子主体与状态流转；发布与挂接回帖", "publish()、addReply()"],
    ["Reply 回帖", "回帖内容与父子层次", "addReply()"],
    ["Tag 标签", "标签实体与热度重算", "recalcHeat()"],
    ["Board 板块", "板块与标签的聚合配置", "aggregate()"],
    ["AiResult 处理结果", "AI 摘要、违规判定与自动标签的载体", "markViolation()、attachTags()"],
]

STATE_HEAD = ["当前状态", "触发事件", "目标状态", "操作者"]
STATE_ROWS = [
    ["（初始）", "① 发布 / 发送", "正常", "用户"],
    ["正常", "② AI 判定违规、命中敏感词或被举报", "待审", "系统 / 用户"],
    ["待审", "③ 审核不成立", "正常（恢复）", "管理员"],
    ["待审", "④ 审核成立", "已删除", "管理员"],
    ["正常", "⑤ 作者删除或管理员处置", "已删除", "用户 / 管理员"],
    ["已删除", "⑥ 撤销处置（24 小时内）", "正常（恢复）", "管理员"],
    ["已删除", "⑦ 记录归档", "终态", "系统"],
]

WEIGHT_HEAD = ["因子", "含义与计算方式", "默认权重"]
WEIGHT_ROWS = [
    ["rel 相关度", "检索得分对本次查询最大值归一化到 [0,1]", "0.5"],
    ["heat 热度", "按 8.3.2 的时间衰减热度再归一化到 [0,1]", "0.3"],
    ["pref 偏好", "内容标签与用户兴趣权重的重合度，归一化到 [0,1]", "0.2"],
]

RULE_HEAD = ["判定条件", "处置动作", "说明"]
RULE_ROWS = [
    ["命中敏感词规则库", "直接置为待审", "规则优先于模型，避免模型漏判"],
    ["模型 violation=true 且 confidence ≥ 0.8", "置为待审，标注“高置信”", "进入人工审核队列尾部"],
    ["0.5 ≤ confidence < 0.8", "置为待审，标注“低置信”", "优先复核，模型可能误判"],
    ["confidence < 0.5", "保持正常，仅留痕", "不打扰用户，记录供后续分析"],
    ["模型服务不可用", "保持正常，标记“待处理”", "由补偿任务重扫，不阻塞发布"],
]


def main():
    doc = Document(SRC)
    R1.DOC = doc
    tpl3 = doc.tables[0]._tbl
    tpl4 = doc.tables[1]._tbl

    def H1(t):
        return R1.new_para(t, style="Heading 1")

    def H2(t):
        return R1.new_para(t, style="Heading 2", space_before=10.0)

    def H3(t):
        return R1.new_para(t, style="Heading 2", space_before=8.0)

    def P(t, **kw):
        return R1.new_para(t, **kw)

    def CAP(t):
        p = R1.new_para(t, align=WD_ALIGN_PARAGRAPH.CENTER, size=9.0)
        p.paragraph_format.keep_with_next = True
        return p

    def FIG(path):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.keep_with_next = True
        p.add_run().add_picture(path, width=Inches(IMG_W))
        return p

    def TBL(template, head, rows, widths):
        sect = doc.element.body.find(
            "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}sectPr")
        sect.addprevious(R1.build_table(template, head, rows, widths))

    H1("八、详细设计——类、状态与关键算法")
    P("概要设计回答“分成几块、块之间怎么调”，本章回答“每块内部怎么实现”："
      "数据与行为怎么组织成类（8.1）、内容在生命周期里怎么流转（8.2）、"
      "三个决定系统好坏的关键算法怎么写（8.3）。")

    # ---- 8.1 -------------------------------------------------------------
    H2("8.1 类设计")
    P("领域类与第六节的关系模式基本一一对应，但类不只是“表 + 字段”："
      "把随状态变化的行为挂到类上，业务规则才有落点（例如“屏蔽消息”属于 Message 而不是某个工具类）。"
      "图 10 给出 8 个核心类及其关联。")
    FIG(os.path.join(WS, "图10-领域类图.png"))
    CAP("图 10  知屿校园平台领域类图")

    P("说明：聊天室与标签、用户与标签的多对多关联已在图 6（E-R 图）与表 7 中给出，"
      "类图只保留能影响行为的主要关联，避免长连线穿过类框。")
    CAP("表 24  核心类的职责与关键方法")
    TBL(tpl3, CLASS_HEAD, CLASS_ROWS, [1500, 3000, 2644])

    P("几点约定：")
    for t in (
        "（1）类的属性一律私有（前缀 -），对外只暴露方法；状态的改变只能通过方法完成，"
        "不允许外部直接改 status，否则审核留痕会丢。",
        "（2）AiResult 不持有 Message/Post 的引用，只按 message_id 或 post_id 二选一关联，"
        "与表 16 的可空外键和 CHECK 约束保持一致。",
        "（3）行为记录的写入不挂在 User 上，而由各模块在关键动作处调用统一的记录入口，"
        "这样新增功能时不会漏埋点。",
    ):
        P(t)

    # ---- 8.2 -------------------------------------------------------------
    H2("8.2 内容状态设计")
    P("消息与帖子共用一套内容状态机：正常、待审、已删除。状态机的价值在于把"
      "“谁能改、什么条件下改”写死，避免各处代码随手改 status。图 11 为状态迁移图。")
    FIG(os.path.join(WS, "图11-内容状态图.png"))
    CAP("图 11  内容状态迁移图")

    CAP("表 25  内容状态迁移表")
    TBL(tpl4, STATE_HEAD, STATE_ROWS, [1200, 2700, 1500, 1744])

    for t in (
        "（1）不存在“直接删除”的路径：任何删除都必须先经过待审或由管理员发起，"
        "对应 UC-11 的处置流程，保证每次删除都有处置人。",
        "（2）删除为逻辑删除（status=2），数据仍在库中，对应 6.1 第 6 条；"
        "物理清理由归档任务在 180 天后执行，对应 NFR-10。",
        "（3）撤销窗口为 24 小时，超时后 ⑥ 不可用，只能走申诉流程。",
    ):
        P(t)

    # ---- 8.3 -------------------------------------------------------------
    H2("8.3 关键算法设计")
    P("本系统有三个决定体验与风险的算法：检索排序（决定用户能否找到内容）、"
      "热度计算（决定推荐是否公平）、违规判定（决定内容安全）。三者都给出公式与阈值，"
      "便于实现与测试。")

    H3("8.3.1 检索排序算法")
    P("检索结果按三因子加权打分后排序，公式如下：")
    P("score(d) = 0.5 × rel(d) + 0.3 × heat(d) + 0.2 × pref(u, d)")
    P("其中 rel 为检索引擎给出的相关度（对本次查询最大值归一化），heat 为内容热度，"
      "pref 为用户偏好；三者都归一到 [0,1]，因此 score 也落在 [0,1]，便于解释与调参。"
      "权重默认值见表 26，可在配置中心调整而不需要改代码。")
    CAP("表 26  检索排序的因子与默认权重")
    TBL(tpl3, WEIGHT_HEAD, WEIGHT_ROWS, [1200, 4000, 1944])

    P("算法步骤（伪代码）：")
    for t in (
        "1  解析查询：分词、去停用词、抽取标签过滤条件；",
        "2  召回：检索引擎返回 Top N（N=200）候选，仅取 status=正常 的内容；",
        "3  对每个候选计算 rel、heat、pref，加权得到 score；",
        "4  按 score 降序，同分时按发布时间倒序（新的优先）；",
        "5  截取前 limit 条（默认 20，上限 50）返回，并写回游标；",
        "6  异步记录本次检索关键词与点击行为到行为日志。",
    ):
        P(t)
    P("复杂度：单次检索为 O(N log N)，N=200 时可忽略；归一化需要一次遍历，O(N)。"
      "检索 P95 ≤ 500 ms 的指标（NFR-02）由“召回上限 200 + 单次打分”保证。")

    H3("8.3.2 热度计算")
    P("热度不能是简单的累计计数，否则老内容永远占优。采用带时间衰减的加权和：")
    P("heat(d) = log(1 + Σ wᵢ × e^(−λ × Δtᵢ))")
    P("其中 wᵢ 为第 i 次互动的权重，Δtᵢ 为距今天数，λ 为衰减系数（默认 0.05，约 14 天减半）。"
      "互动权重：浏览 1、停留每 10 秒 1、点赞 3、收藏 4、回帖 3、发帖 5。")
    P("实现方式：heat 作为冗余字段存于 post/tag 表（对应 6.1 第 7 条），"
      "由定时任务每小时按行为日志重算，而不是每次查询实时聚合，避免大表扫描。")

    H3("8.3.3 违规判定与转人工")
    P("违规判定采用“规则 + 模型 + 人工”三层，任何一层都不单独决定删除，只决定是否进入待审。"
      "判定规则见表 27。")
    CAP("表 27  违规判定规则与处置动作")
    TBL(tpl3, RULE_HEAD, RULE_ROWS, [2800, 2100, 2244])

    P("两条硬性约束：")
    for t in (
        "（1）模型只做“标记”，不做“删除”。即使 confidence=0.99，内容也只进入待审，"
        "由管理员确认——对应 NFR-08 的“违规内容 100% 进入拦截或人工审核”。",
        "（2）低置信区间（0.5~0.8）单独标注并优先复核，因为这部分最容易误判；"
        "统计这两个区间的人工推翻率，可作为后续调阈值的依据。",
    ):
        P(t)

    # ---- 8.4 -------------------------------------------------------------
    H2("8.4 本章与其他章节的对应")
    for t in (
        "（1）类 ↔ 表：图 10 的 8 个类对应第六节 18 张表中的 8 张主表，"
        "其余 10 张关联表在类图中体现为集合属性或独立仓储，不单独建类。",
        "（2）状态 ↔ 用例：图 11 的 ①② 对应 UC-06 发帖与 UC-10 智能体处理，"
        "③④ 对应 UC-11 审核处置，⑤ 对应 UC-07 与 UC-11 的删除动作。",
        "（3）算法 ↔ 指标：8.3.1 的召回上限对应 NFR-02（P95 ≤ 500 ms），"
        "8.3.3 的阈值对应 NFR-08（违规内容 100% 审核）。",
        "（4）接口 ↔ 实现：表 21 的接口在本章都能找到落点，"
        "例如 A-19 检索对应 8.3.1，A-22 审核处置对应图 11 的 ③④。",
    ):
        P(t)
    P("至此详细设计的核心内容完成。下一轮进入测试：按表 21 的 23 个接口与表 27 的判定规则"
      "逐条设计测试用例，覆盖正常流、备选流与错误码。")

    doc.save(OUT)
    print("saved:", OUT)


if __name__ == "__main__":
    main()
